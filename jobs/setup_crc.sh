#!/bin/bash
# Run once on the CRC front end after git pull. No capture is started.
set -euo pipefail
umask 077
cd "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
if [[ "$(uname -s)" != Linux ]]; then
    echo 'Run this setup on the Linux CRC front end; your Mac tda environment is already configured.' >&2
    exit 2
fi
if [[ -f jobs/crc_capture.local.sh ]]; then
    source jobs/crc_capture.local.sh
fi

# CRC documents module load conda for initial setup only. No conda init or
# changes to shell startup files are necessary because we save conda.sh.
if [[ -z "${CONDA_SH:-}" && ! -f jobs/crc_conda.local.sh ]] && ! command -v conda >/dev/null 2>&1; then
    if ! type module >/dev/null 2>&1 && [[ -r /etc/profile.d/modules.sh ]]; then
        source /etc/profile.d/modules.sh
    fi
    if type module >/dev/null 2>&1; then
        module load conda
    fi
fi
source jobs/crc_conda.sh
initialize_crc_conda

crc_environments="$(conda env list)"
if awk '$1 == "tda" {found=1} END {exit !found}' <<< "$crc_environments"; then
    echo 'Updating the collector dependencies in the existing CRC tda environment.'
    # Keep any unrelated research packages in an existing environment.
    conda env update --name tda --file environment-crc.yml
else
    echo 'Creating the CRC tda environment from environment-crc.yml.'
    conda env create --file environment-crc.yml
fi
conda activate tda
python -c 'import sys, cryptography, websocket, jwt; assert sys.version_info >= (3, 11); print("Capture Python:", sys.executable); print("Dependencies:", cryptography.__version__, websocket.__version__, jwt.__version__)'
python -B -m unittest discover -s tests -v

# Write only after environment creation and validation succeed. %q preserves
# spaces and shell metacharacters without treating paths as shell commands.
temporary_config="$(mktemp jobs/crc_conda.local.sh.XXXXXX)"
trap 'rm -f "$temporary_config"' EXIT
printf '# Generated by setup_crc.sh on CRC; ignored by Git.\nCONDA_SH=%q\n' "$CONDA_SH" > "$temporary_config"
chmod 600 "$temporary_config"
mv "$temporary_config" jobs/crc_conda.local.sh
trap - EXIT
printf '\nCRC tda environment is ready. The batch job will activate it automatically.\n'
printf 'After configuring your key paths and checking quota, submit:\n  qsub jobs/kalshi_btc_crc.job\n'
